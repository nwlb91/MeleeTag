#!/usr/bin/env python3
"""Write boot_syms.h for boot_test.c from the build outputs.

Usage: gen_syms.py <gale01_syms.ld> <payload.elf> <payload.sites> <out.h> <nm>
"""
import re
import subprocess
import sys

ENGINE = ["OSGetArenaHi", "OSGetArenaLo", "OSSetArenaHi", "DCFlushRange",
          "ICInvalidateRange", "memcpy"]
PAYLOAD = ["tag_g", "tag_config", "tag_rules_map_jumps",
           "tag_rules_state_class", "tag_rules_entry"]


def main():
    ld, elf, sites, out, nm = sys.argv[1:6]
    engine = {}
    for line in open(ld):
        m = re.match(r"PROVIDE\((\w+) = 0x([0-9A-Fa-f]+)\);", line)
        if m and m.group(1) in ENGINE:
            engine[m.group(1)] = int(m.group(2), 16)
    payload = {}
    for line in subprocess.check_output([nm, elf], text=True).splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] in PAYLOAD:
            payload[parts[2]] = int(parts[0], 16)
    site_lines = [l.split() for l in open(sites) if l.strip()]
    boot = int(site_lines[0][0], 16)
    hooks = [int(s[0], 16) for s in site_lines[1:]]
    missing = [n for n in ENGINE if n not in engine] + \
              [n for n in PAYLOAD if n not in payload]
    if missing:
        sys.exit("missing symbols: " + ", ".join(missing))
    with open(out, "w") as f:
        f.write("/* Generated by tests/qemu/gen_syms.py */\n")
        for n in ENGINE:
            f.write(f"#define SYM_{n} 0x{engine[n]:08X}u\n")
        for n in PAYLOAD:
            f.write(f"#define SYM_{n} 0x{payload[n]:08X}u\n")
        f.write(f"#define SYM_BOOT_SITE 0x{boot:08X}u\n")
        f.write(f"#define SYM_HOOK_COUNT {len(hooks)}u\n")
        f.write("static const unsigned sym_hook_sites[] = { " +
                ", ".join(f"0x{h:08X}u" for h in hooks) + " };\n")


if __name__ == "__main__":
    main()
