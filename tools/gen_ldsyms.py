#!/usr/bin/env python3
"""Generate a GNU ld symbol script from the decomp's symbols.txt.

Every global/local function and object in the retail NTSC 1.02 DOL is emitted
as `PROVIDE(name = 0xADDRESS);` so the mod can call engine functions and
reference engine data by their decomp names.  Names that appear more than once
(file-local statics sharing a name) are ambiguous and are skipped; the mod must
never reference them.

Usage: gen_ldsyms.py <symbols.txt> <out.ld>
"""

import re
import sys

LINE = re.compile(
    r"^(?P<name>\S+) = (?P<section>\.\w+|extab|extabindex):0x(?P<addr>[0-9A-Fa-f]{8});"
)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    seen: dict[str, int] = {}
    dupes: set[str] = set()
    with open(src, encoding="utf-8") as f:
        for raw in f:
            m = LINE.match(raw.strip())
            if not m:
                continue
            name = m.group("name")
            addr = int(m.group("addr"), 16)
            if name in seen and seen[name] != addr:
                dupes.add(name)
            seen[name] = addr
    with open(dst, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_ldsyms.py from the decomp's symbols.txt. */\n")
        for name in sorted(seen):
            if name in dupes:
                continue
            # ld symbol names cannot contain some characters used by the decomp
            # for anonymous data (e.g. "@1234"); those are never referenced.
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                continue
            out.write(f"PROVIDE({name} = 0x{seen[name]:08X});\n")
    print(f"{dst}: {len(seen) - len(dupes)} symbols ({len(dupes)} ambiguous skipped)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
